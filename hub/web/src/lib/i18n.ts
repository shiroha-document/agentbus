export type Language = "zh" | "en";
export const LANGUAGE_KEY = "agentbus.language";
export const LANGUAGE_LABEL: Record<Language, string> = { zh: "简体中文", en: "English" };
export const LOCALE: Record<Language, string> = { zh: "zh-CN", en: "en-US" };

interface LanguageStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}
interface LanguageOptions {
  browserLanguage?: string;
  storage?: LanguageStorage | null;
  html?: { lang: string };
  onChange?: (language: Language) => void;
}

function detectLanguage(browserLanguage?: string): Language {
  return browserLanguage?.toLowerCase().startsWith("zh") ? "zh" : "en";
}
function parseLanguage(value: unknown): Language | null {
  return value === "zh" || value === "en" ? value : null;
}

/** An in-memory preference remains usable when the browser blocks storage. */
export function createLanguageStore({ browserLanguage, storage, html, onChange }: LanguageOptions = {}) {
  const fallback = detectLanguage(browserLanguage);
  let language = fallback;
  try { language = parseLanguage(storage?.getItem(LANGUAGE_KEY)) ?? fallback; } catch { /* blocked storage */ }
  const listeners = new Set<() => void>();
  const paint = () => {
    if (html) html.lang = language === "en" ? "en" : "zh-CN";
    onChange?.(language);
  };
  const apply = (next: Language) => {
    const changed = next !== language;
    language = next;
    paint();
    if (changed) listeners.forEach((listener) => listener());
  };
  paint();
  return {
    getSnapshot: () => language,
    subscribe(listener: () => void) { listeners.add(listener); return () => { listeners.delete(listener); }; },
    setLanguage(next: Language) {
      if (!parseLanguage(next)) return;
      try { storage?.setItem(LANGUAGE_KEY, next); } catch { /* retain the in-memory choice */ }
      apply(next);
    },
    syncStoredLanguage(value: string | null) { apply(parseLanguage(value) ?? fallback); },
  };
}

function browserOptions(): LanguageOptions {
  if (typeof window === "undefined") return {};
  let storage: LanguageStorage | null = null;
  try { storage = window.localStorage; } catch { /* privacy settings */ }
  return { browserLanguage: window.navigator?.language, storage, html: typeof document === "undefined" ? undefined : document.documentElement,
    onChange: (language) => {
      if (typeof document !== "undefined") document.querySelector?.('link[rel="manifest"]')?.setAttribute("href", manifestUrl(language));
    },
  };
}
const languageStore = createLanguageStore(browserOptions());
if (typeof window !== "undefined") {
  window.addEventListener("storage", (event) => {
    if (event.key === LANGUAGE_KEY || event.key === null) languageStore.syncStoredLanguage(event.newValue);
  });
}
export const getLanguage = languageStore.getSnapshot;
export const setLanguage = languageStore.setLanguage;
export function useLanguage(): Language {
  return useSyncExternalStore(languageStore.subscribe, getLanguage, getLanguage);
}
export function getLocale(language = getLanguage()): string { return LOCALE[language]; }

