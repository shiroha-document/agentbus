export type TranslationKey = keyof typeof dictionary;
export function t(key: TranslationKey, values: readonly unknown[] = [], language = getLanguage()): string {
  const template: string = dictionary[key][language === "zh" ? 0 : 1];
  return template.replace(/\{(\d+)\}/g, (match, index: string) => index in values ? String(values[Number(index)] ?? "") : match);
}
/** Only for server-authored system copy; member content must never use this lookup. */
export function systemText(text: string): string {
  return Object.hasOwn(dictionary, text) ? t(text as TranslationKey) : text;
}
