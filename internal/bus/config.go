package bus

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Config is persisted at $AGENTBUS_HOME/config.json (default ~/.agentbus).
// One home = one agent identity. Run several agents on one machine by giving
// each its own AGENTBUS_HOME.
type Config struct {
	Remote string `json:"remote"`
	Branch string `json:"branch"`
	Me     string `json:"me"`
	SSHKey string `json:"ssh_key,omitempty"` // private key path generated by `join`
}

// Home resolves the agentbus home directory.
func Home() string {
	if h := os.Getenv("AGENTBUS_HOME"); h != "" {
		return h
	}
	if h, err := os.UserHomeDir(); err == nil {
		return filepath.Join(h, ".agentbus")
	}
	return ".agentbus"
}

func configPath(home string) string { return filepath.Join(home, "config.json") }
func clonePath(home string) string  { return filepath.Join(home, "clone") }
func statePath(home string) string  { return filepath.Join(home, "state.json") }

// LoadConfig reads the config from home.
func LoadConfig(home string) (*Config, error) {
	b, err := os.ReadFile(configPath(home))
	if errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("not initialised: run `agentbus init --remote <git-url> --me <name>` (home %s)", home)
	}
	if err != nil {
		return nil, err
	}
	var c Config
	if err := json.Unmarshal(b, &c); err != nil {
		return nil, err
	}
	return &c, nil
}

// SaveConfig writes the config to home.
func SaveConfig(home string, c *Config) error {
	if err := os.MkdirAll(home, 0o700); err != nil {
		return err
	}
	b, _ := json.MarshalIndent(c, "", "  ")
	return os.WriteFile(configPath(home), b, 0o600)
}

// ValidName reports whether s is a legal agent/channel name.
func ValidName(s string) bool {
	if len(s) < 2 || len(s) > 40 || s == "human" {
		return s == "human"
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.') {
			return false
		}
	}
	return !strings.HasPrefix(s, ".")
}

// State is local, per-agent and never pushed: which events were already
// surfaced to this agent (for `inbox --new` / `wait`).
type State struct {
	Seen map[string]bool `json:"seen"`
}

func loadState(home string) *State {
	s := &State{Seen: map[string]bool{}}
	if b, err := os.ReadFile(statePath(home)); err == nil {
		_ = json.Unmarshal(b, s)
		if s.Seen == nil {
			s.Seen = map[string]bool{}
		}
	}
	return s
}

func (s *State) save(home string) error {
	b, _ := json.Marshal(s)
	tmp := statePath(home) + ".tmp"
	if err := os.WriteFile(tmp, b, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, statePath(home))
}
